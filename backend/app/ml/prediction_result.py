"""
Prediction Result Model.
Defines the structure of the output generated by the Prediction Engine.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class PredictionResult:
    """
    The final output of a cricket prediction.
    """

    predicted_runs: float
    wicket_probability: float
    confidence: float
    analysis: list[str] = field(default_factory=list)

    # NEW: Added for 90% accuracy bracketing
    expected_range: str = ""

    # NEW (2026-08-23): probability the currently-batting team wins the
    # match, from match_winner_v1 -- see docs/finding_match_winner_v1.md.
    # A third prediction alongside runs/wicket, not a replacement.
    win_probability: float = 0.5

    # NEW: Added to support additional match insights
    metadata: dict = field(default_factory=dict)

    @property
    def confidence_percent(self) -> int:
        """Return confidence as a whole-number percentage."""
        return round(self.confidence * 100)

    @property
    def confidence_level(self) -> str:
        """Return a compact user-facing confidence category.

        Thresholds are set against the *calibrated* confidence scale (see
        fit_confidence_calibrator.py), not the raw 0-1 heuristic. Calibrated
        against real range-hit outcomes, confidence is heavily concentrated
        around ~0.337 (p10-p75 on a 764-over sample were all exactly this
        value) with a thin tail up to ~0.38 -- the old 0.60/0.80 thresholds
        would have shown "LOW" on almost every prediction post-calibration.
        These bands are set relative to that real, narrow distribution so
        the label still carries some signal instead of being degenerate.
        """
        if self.confidence >= 0.35:
            return "HIGH"
        if self.confidence >= 0.25:
            return "MEDIUM"
        return "LOW"

    @property
    def confidence_meter(self) -> str:
        """Return a ten-segment confidence meter suitable for text displays."""
        filled = min(10, max(0, round(self.confidence * 10)))
        return "█" * filled + "░" * (10 - filled)

    def validate(self) -> bool:
        """Validate the normalized prediction values used by persisted models."""
        if self.predicted_runs < 0:
            raise ValueError("Predicted runs cannot be negative.")

        if not 0.0 <= self.wicket_probability <= 1.0:
            raise ValueError("Wicket probability must be between 0 and 1.")

        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("Confidence must be between 0 and 1.")

        if not 0.0 <= self.win_probability <= 1.0:
            raise ValueError("Win probability must be between 0 and 1.")

        return True

    def to_dict(self) -> dict:
        """Converts result to a dictionary for JSON output."""
        return {
            "expected_runs": self.predicted_runs,
            "expected_range": self.expected_range,
            "wicket_probability": self.wicket_probability,
            "win_probability": self.win_probability,
            "confidence": self.confidence,
            "confidence_percent": self.confidence_percent,
            "confidence_level": self.confidence_level,
            "confidence_meter": self.confidence_meter,
            "analysis": self.analysis,
            "metadata": self.metadata,
        }
